/** Рисует иконку в квадрат size×size с левым верхним углом в (x, y). */
export function drawIcon(ctx, name, x, y, size, { color, width }) {
  const icon = ICONS[name];
  if (!icon) return false;

  const k = size / 32;
  ctx.save();
  ctx.translate(x, y);
  ctx.scale(k, k);
  ctx.strokeStyle = color;
  ctx.lineWidth = width / k;
  ctx.lineCap = 'round';
  ctx.lineJoin = 'round';
  ctx.fillStyle = 'transparent';

  for (const d of icon.paths ?? []) ctx.stroke(new Path2D(d));
  for (const [cx, cy, r] of icon.circles ?? []) {
    const circle = new Path2D();
    circle.arc(cx, cy, r, 0, Math.PI * 2);
    // мелкие точки штрихом сливаются в пятно — их честнее залить
    if (r < 1.6) {
      ctx.fillStyle = color;
      ctx.fill(circle);
      ctx.fillStyle = 'transparent';
    } else {
      ctx.stroke(circle);
    }
  }
  ctx.restore();
  return true;
}
